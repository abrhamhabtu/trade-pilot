// The same sweep-and-reversal reader as Vision, as a TradingView indicator.
// It marks the three steps (prior swing, sweep, confirmation), draws the plan
// and fires an alert whose JSON the TradePilot webhook understands, so a
// TradingView alert can feed Proving Ground's "My TradingView signals" tests.
//
// It mirrors analyze.ts closely but not exactly: TradingView has no access to
// this app's history replay, so its target is the nearest opposite swing at
// 1.2R or more, else 2R, capped at the chosen maximum.

export function visionPine(opts: { key?: string } = {}) {
  const key = (opts.key ?? "").replace(/[^A-Za-z0-9_-]/g, "").slice(0, 64);
  return `//@version=6
// TradePilot Vision · Sweep & Reversal
// Generated by TradePilot. Marks liquidity sweeps that reverse, with the plan.
indicator("TradePilot Vision · Sweep & Reversal", shorttitle = "TP Vision", overlay = true, max_labels_count = 300, max_lines_count = 300)

grp       = "Reader"
span      = input.int(3, "Swing strength (bars each side)", minval = 1, group = grp)
lookback  = input.int(60, "Swing lookback (bars)", minval = 10, group = grp)
window    = input.int(6, "Confirm within N bars of the sweep", minval = 1, group = grp)
emaLen    = input.int(21, "EMA length", minval = 2, group = grp)
maxR      = input.float(4.0, "Largest target (R)", minval = 1.0, step = 0.5, group = grp)
grpD      = "Display"
showSteps = input.bool(true, "Number the steps (1 swing, 2 sweep, 3 confirm)", group = grpD)
showPlan  = input.bool(true, "Draw entry, stop and target", group = grpD)
accent    = input.color(#FF8A3D, "Accent", group = grpD)
grpA      = "Alerts"
KEY       = input.string("${key}", "TradePilot webhook key", group = grpA)

ema21 = ta.ema(close, emaLen)
a     = ta.atr(14)
r     = ta.rsi(close, 14)
plot(ema21, "EMA", color.new(color.white, 45), 2)

ph = ta.pivothigh(high, span, span)
pl = ta.pivotlow(low, span, span)

// The most recent swing on each side that has not been taken yet.
var float loLvl = na
var int   loBar = na
var float hiLvl = na
var int   hiBar = na
if not na(pl)
    loLvl := pl
    loBar := bar_index - span
if not na(ph)
    hiLvl := ph
    hiBar := bar_index - span

// Sweeps: a wick through the swing that closes back near or across it.
var int   swL = na
var float swLow = na
var int   swH = na
var float swHigh = na
if not na(loLvl) and bar_index - loBar <= lookback and low < loLvl - 0.05 * a and close > loLvl - 0.3 * a and na(swL)
    swL := bar_index
    swLow := low
if not na(hiLvl) and bar_index - hiBar <= lookback and high > hiLvl + 0.05 * a and close < hiLvl + 0.3 * a and na(swH)
    swH := bar_index
    swHigh := high
// A new extreme after the sweep cancels it; so does running out of time.
if not na(swL) and (low < swLow or bar_index - swL > window)
    swL := na
if not na(swH) and (high > swHigh or bar_index - swH > window)
    swH := na

longOk  = not na(swL) and close > loLvl and (close > ema21 or (r > r[2] and close > open))
shortOk = not na(swH) and close < hiLvl and (close < ema21 or (r < r[2] and close < open))
longSig  = longOk and not longOk[1]
shortSig = shortOk and not shortOk[1]

f_target(bool isLong, float entry, float risk) =>
    float t = isLong ? entry + 2 * risk : entry - 2 * risk
    float opp = isLong ? hiLvl : loLvl
    if not na(opp) and (isLong ? opp - entry >= 1.2 * risk : entry - opp >= 1.2 * risk)
        t := opp
    isLong ? math.min(t, entry + maxR * risk) : math.max(t, entry - maxR * risk)

f_payload(string side, float stop, float target) =>
    '{"key":"' + KEY + '","setup":"vision-sweep","side":"' + side + '","symbol":"' + syminfo.ticker + '","price":' + str.tostring(close) + ',"stop":' + str.tostring(stop) + ',"target":' + str.tostring(target) + ',"tf":"' + timeframe.period + '"}'

f_draw(bool isLong, int lvlBar, float lvl, int swBar, float swPx, float stop, float target) =>
    if showSteps
        label.new(lvlBar, lvl, "1", style = isLong ? label.style_label_up : label.style_label_down, color = accent, textcolor = color.black, size = size.small)
        label.new(swBar, swPx, "2", style = isLong ? label.style_label_up : label.style_label_down, color = accent, textcolor = color.black, size = size.small)
        label.new(bar_index, close, "3 " + (isLong ? "LONG" : "SHORT"), style = isLong ? label.style_label_up : label.style_label_down, color = color.white, textcolor = color.black, size = size.small)
        line.new(lvlBar, lvl, bar_index, lvl, color = color.new(accent, 30), style = line.style_dashed)
    if showPlan
        line.new(bar_index, close, bar_index + 20, close, color = color.new(color.white, 30), style = line.style_dotted)
        line.new(bar_index, target, bar_index + 20, target, color = accent, width = 2)
        line.new(bar_index, stop, bar_index + 20, stop, color = color.new(color.red, 0), width = 2)

if longSig
    float stop = math.min(swLow, ta.lowest(low, math.max(1, bar_index - swL + 1))) - 0.15 * a
    float tgt = f_target(true, close, close - stop)
    f_draw(true, loBar, loLvl, swL, swLow, stop, tgt)
    alert(f_payload("long", stop, tgt), alert.freq_once_per_bar_close)
    swL := na
    loLvl := na
if shortSig
    float stop = math.max(swHigh, ta.highest(high, math.max(1, bar_index - swH + 1))) + 0.15 * a
    float tgt = f_target(false, close, stop - close)
    f_draw(false, hiBar, hiLvl, swH, swHigh, stop, tgt)
    alert(f_payload("short", stop, tgt), alert.freq_once_per_bar_close)
    swH := na
    hiLvl := na

plotshape(longSig, "Long", shape.triangleup, location.belowbar, accent, size = size.tiny)
plotshape(shortSig, "Short", shape.triangledown, location.abovebar, color.white, size = size.tiny)
`;
}
